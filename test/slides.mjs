import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import path from "node:path";
import fs from "node:fs";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const c = new Client({ name: "slides", version: "1" });
await c.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(here, "..", "server.mjs")] }));
const call = async (n, a) => { const r = await c.callTool({ name: n, arguments: a }); const t = r.content.filter(x => x.type === "text").map(x => x.text).join("\n"); console.log(r.isError ? "✘" : "✔", n, r.isError ? t.slice(0, 300) : ""); return t; };
await call("ps_new_document", { name: "VZ carrusel", slides: { count: 3, width: 1080, height: 1350 }, width: 1080, height: 1350, background: "#0B0F0C" });
const info = JSON.parse(await call("ps_document_info", {}));
console.log("tamaño", info.width, info.height, "guías", JSON.stringify(info.guides));
await call("ps_add_shape", { shape: "ellipse", x: 800, y: 300, width: 1400, height: 700, fill: "#419947", blend: "screen", fillOpacity: 50, name: "Luz que cruza" });
const out = (await import("node:os")).tmpdir().split("\\").join("/") + "/vz_slides";
fs.rmSync(out, { recursive: true, force: true });
await call("ps_export", { folder: out, name: "carrusel", format: "jpg", mode: "slides", quality: 85 });
console.log(fs.readdirSync(out).join(", "));
await call("ps_close", { doc: "VZ carrusel", save: false });
await c.close(); process.exit(0);
