import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const client = new Client({ name: "lista", version: "1.0.0" });
await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(here, "..", "server.mjs")] }));
const tools = (await client.listTools()).tools;
console.log(tools.length, "herramientas");
for (const t of tools) console.log("-", t.name, `(${JSON.stringify(t.inputSchema).length} B)`);
await client.close(); process.exit(0);
